'use strict';

const fs = require('fs');
const path = require('path');
const { androidPackName } = require('./props.cjs');

const SETTINGS_BEGIN = '// @generated begin react-native-nitro-assets';
const SETTINGS_END = '// @generated end react-native-nitro-assets';
/** Manifest meta-data that tells the native module which packs exist and how they are delivered. */
const PACKS_META_DATA = 'com.margelo.nitro.assets.packs';

const DELIVERY_TYPE = { 'install-time': 'install-time', 'fast-follow': 'fast-follow', 'on-demand': 'on-demand' };

function stripBlock(contents) {
  const pattern = new RegExp(`\\n?${SETTINGS_BEGIN}[\\s\\S]*?${SETTINGS_END}\\n?`, 'g');
  return contents.replace(pattern, '\n');
}

/** `include ':intent_model'` per pack, in a generated block that is replaced on every prebuild. */
function applySettingsGradle(contents, { playAssetDelivery }, language = 'groovy') {
  const lines = Object.keys(playAssetDelivery.packs).map((packId) =>
    language === 'kt' ? `include(":${androidPackName(packId)}")` : `include ':${androidPackName(packId)}'`,
  );
  return `${stripBlock(contents).trimEnd()}\n${SETTINGS_BEGIN}\n${lines.join('\n')}\n${SETTINGS_END}\n`;
}

/** `assetPacks = [":intent_model"]` at the top of the app module's `android {}` block. */
function applyAppBuildGradle(contents, { playAssetDelivery }, language = 'groovy') {
  const names = Object.keys(playAssetDelivery.packs).map((packId) => `":${androidPackName(packId)}"`);
  const line =
    language === 'kt'
      ? `    assetPacks += listOf(${names.join(', ')})`
      : `    assetPacks = [${names.join(', ')}]`;
  const block = `    ${SETTINGS_BEGIN}\n${line}\n    ${SETTINGS_END}`;
  const cleaned = contents.replace(
    new RegExp(`\\n?[ \\t]*${SETTINGS_BEGIN}[\\s\\S]*?${SETTINGS_END}`, 'g'),
    '',
  );
  const anchor = /^android\s*\{\s*$/m;
  if (!anchor.test(cleaned))
    throw new Error('react-native-nitro-assets: no "android {" block in android/app/build.gradle');
  return cleaned.replace(anchor, (match) => `${match}\n${block}`);
}

function assetPackBuildGradle(packId, deliveryType) {
  return [
    '// Generated by react-native-nitro-assets. Edit the config plugin options instead.',
    "plugins {",
    "    id 'com.android.asset-pack'",
    '}',
    '',
    'assetPack {',
    `    packName = "${androidPackName(packId)}"`,
    '    dynamicDelivery {',
    `        deliveryType = "${DELIVERY_TYPE[deliveryType]}"`,
    '    }',
    '}',
    '',
  ].join('\n');
}

/**
 * Writes one asset-pack module per pack: `android/<name>/build.gradle` and the pack's files under
 * `android/<name>/src/main/assets/<packId>/` (every backend keeps a pack's files under its id).
 */
function writeAssetPackModules({ projectRoot, platformProjectRoot, packs, playAssetDelivery }) {
  for (const [packId, deliveryType] of Object.entries(playAssetDelivery.packs)) {
    const source = path.resolve(projectRoot, packs[packId].path);
    if (!fs.existsSync(source) || !fs.statSync(source).isDirectory())
      throw new Error(`react-native-nitro-assets: packs["${packId}"].path (${source}) is not a directory`);
    const moduleDir = path.join(platformProjectRoot, androidPackName(packId));
    fs.rmSync(moduleDir, { recursive: true, force: true });
    const assetsDir = path.join(moduleDir, 'src', 'main', 'assets', packId);
    fs.mkdirSync(path.dirname(assetsDir), { recursive: true });
    fs.cpSync(source, assetsDir, { recursive: true, dereference: true, filter: (file) => path.basename(file) !== '.DS_Store' });
    fs.writeFileSync(path.join(moduleDir, 'build.gradle'), assetPackBuildGradle(packId, deliveryType));
  }
}

/** `packId=deliveryType;…`, read by the Kotlin module to know the packs and how to open them. */
function packsMetaDataValue({ playAssetDelivery }) {
  return Object.entries(playAssetDelivery.packs)
    .map(([packId, deliveryType]) => `${packId}=${deliveryType}`)
    .join(';');
}

/** Adds or replaces the packs meta-data on the manifest's `<application>`. */
function applyManifest(manifest, props) {
  const application = manifest.manifest.application && manifest.manifest.application[0];
  if (!application) throw new Error('react-native-nitro-assets: AndroidManifest.xml has no <application>');
  const metaData = (application['meta-data'] || []).filter(
    (item) => item.$['android:name'] !== PACKS_META_DATA,
  );
  metaData.push({ $: { 'android:name': PACKS_META_DATA, 'android:value': packsMetaDataValue(props) } });
  application['meta-data'] = metaData;
  return manifest;
}

module.exports = {
  PACKS_META_DATA,
  applyAppBuildGradle,
  applyManifest,
  applySettingsGradle,
  assetPackBuildGradle,
  packsMetaDataValue,
  writeAssetPackModules,
};
